-- 1. Users and Roles
CREATE TABLE fc_users (
    user_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR2(50) NOT NULL UNIQUE,
    full_name        VARCHAR2(100) NOT NULL,
    email            VARCHAR2(100) NOT NULL,
    office           VARCHAR2(10) DEFAULT 'SG' NOT NULL CHECK (office IN ('SG', 'JKT')),
    is_active        VARCHAR2(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    created_at       TIMESTAMP WITH LOCAL TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE fc_user_roles (
    role_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR2(50) NOT NULL,
    role_code        VARCHAR2(30) NOT NULL,
    assigned_at      TIMESTAMP WITH LOCAL TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_fc_roles_user FOREIGN KEY (username) REFERENCES fc_users (username) ON DELETE CASCADE,
    CONSTRAINT uk_fc_user_role UNIQUE (username, role_code)
);

-- 2. Tenders (Pitches)
CREATE TABLE fc_tenders (
    tender_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tender_code         VARCHAR2(30) NOT NULL UNIQUE,
    client_name         VARCHAR2(100) NOT NULL,
    project_title       VARCHAR2(200) NOT NULL,
    office              VARCHAR2(10) DEFAULT 'SG' NOT NULL CHECK (office IN ('SG', 'JKT')),
    current_stage       VARCHAR2(30) DEFAULT 'INTAKE_REVIEW' NOT NULL,
    status              VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'BLOCKED', 'CHANGES_REQUESTED', 'ON_HOLD', 'RELEASED', 'ARCHIVED')),
    submission_deadline DATE NOT NULL,
    primary_currency    VARCHAR2(5) DEFAULT 'SGD' NOT NULL CHECK (primary_currency IN ('SGD', 'IDR', 'USD')),
    sponsor_user        VARCHAR2(50) NOT NULL,
    planning_lead       VARCHAR2(50) NOT NULL,
    designer_user       VARCHAR2(50) NOT NULL,
    ops_lead            VARCHAR2(50) NOT NULL,
    delegate_user       VARCHAR2(50),
    is_confidential     VARCHAR2(1) DEFAULT 'N' NOT NULL CHECK (is_confidential IN ('Y', 'N')),
    total_cost          NUMBER(14,2) DEFAULT 0,
    total_price         NUMBER(14,2) DEFAULT 0,
    margin_pct          NUMBER(6,2) DEFAULT 25.00,
    markup_pct          NUMBER(6,2) DEFAULT 33.33,
    deal_progression    VARCHAR2(30) DEFAULT 'IN_PROGRESS' NOT NULL CHECK (deal_progression IN ('PITCHING', 'IN_PROGRESS', 'DEAL_CLOSED', 'DEAL_LOST')),
    deal_value          NUMBER(14,2),
    deal_won_date       DATE,
    created_by          VARCHAR2(50) DEFAULT USER NOT NULL,
    created_at          TIMESTAMP WITH LOCAL TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_by          VARCHAR2(50) DEFAULT USER NOT NULL,
    updated_at          TIMESTAMP WITH LOCAL TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_fc_tenders_office ON fc_tenders (office, current_stage, status);

