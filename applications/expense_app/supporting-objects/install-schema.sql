-- =============================================================================
-- Schema Definition: Expense Approval Workflow
-- Compatible with Oracle Database 19c, 23ai, and 26ai
-- Feature: 002-expense-approval-workflow
-- =============================================================================

-- 1. Reference Categories Lookup
CREATE TABLE exp_category (
    category_code       VARCHAR2(30)   NOT NULL,
    category_name       VARCHAR2(100)  NOT NULL,
    is_active           CHAR(1)        DEFAULT 'Y' NOT NULL,
    created_at          DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_exp_category PRIMARY KEY (category_code),
    CONSTRAINT chk_exp_cat_active CHECK (is_active IN ('Y', 'N'))
);

-- 2. User Profiles & Hierarchy (Decision R-001)
CREATE TABLE exp_user_profile (
    username            VARCHAR2(100)  NOT NULL,
    full_name           VARCHAR2(200)  NOT NULL,
    email               VARCHAR2(255)  NOT NULL,
    system_role         VARCHAR2(30)   NOT NULL,
    manager_username    VARCHAR2(100),
    director_username   VARCHAR2(100),
    is_active           CHAR(1)        DEFAULT 'Y' NOT NULL,
    created_at          DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_exp_user_profile PRIMARY KEY (username),
    CONSTRAINT fk_exp_user_mgr FOREIGN KEY (manager_username) REFERENCES exp_user_profile(username),
    CONSTRAINT fk_exp_user_dir FOREIGN KEY (director_username) REFERENCES exp_user_profile(username),
    CONSTRAINT chk_exp_user_role CHECK (system_role IN ('EMPLOYEE', 'MANAGER', 'DIRECTOR', 'ADMIN')),
    CONSTRAINT chk_exp_user_active CHECK (is_active IN ('Y', 'N'))
);

-- 3. Master Expense Claim Table
CREATE TABLE exp_claim (
    claim_id            NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_number        VARCHAR2(30)   NOT NULL,
    submitter_username  VARCHAR2(100)  NOT NULL,
    business_purpose    VARCHAR2(500)  NOT NULL,
    total_amount        NUMBER(12,2)   DEFAULT 0.00 NOT NULL,
    current_status      VARCHAR2(30)   DEFAULT 'DRAFT' NOT NULL,
    current_stage       VARCHAR2(30)   DEFAULT 'NONE' NOT NULL,
    assigned_approver   VARCHAR2(100),
    created_at          DATE           DEFAULT SYSDATE NOT NULL,
    submitted_at        DATE,
    final_approved_at   DATE,
    rejected_at         DATE,
    row_version         NUMBER         DEFAULT 1 NOT NULL,
    CONSTRAINT pk_exp_claim PRIMARY KEY (claim_id),
    CONSTRAINT uq_exp_claim_num UNIQUE (claim_number),
    CONSTRAINT fk_exp_claim_submitter FOREIGN KEY (submitter_username) REFERENCES exp_user_profile(username),
    CONSTRAINT fk_exp_claim_approver FOREIGN KEY (assigned_approver) REFERENCES exp_user_profile(username),
    CONSTRAINT chk_exp_claim_status CHECK (current_status IN ('DRAFT', 'PENDING_MANAGER', 'PENDING_DIRECTOR', 'APPROVED', 'REJECTED')),
    CONSTRAINT chk_exp_claim_stage CHECK (current_stage IN ('NONE', 'MANAGER', 'DIRECTOR')),
    CONSTRAINT chk_exp_claim_total CHECK (total_amount >= 0.00)
);

-- 4. Line Items Table (BR-EXP-001)
CREATE TABLE exp_claim_item (
    item_id             NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_id            NUMBER         NOT NULL,
    expense_date        DATE           NOT NULL,
    category_code       VARCHAR2(30)   NOT NULL,
    description         VARCHAR2(400)  NOT NULL,
    amount              NUMBER(10,2)   NOT NULL,
    created_at          DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_exp_claim_item PRIMARY KEY (item_id),
    CONSTRAINT fk_exp_item_claim FOREIGN KEY (claim_id) REFERENCES exp_claim(claim_id) ON DELETE CASCADE,
    CONSTRAINT fk_exp_item_cat FOREIGN KEY (category_code) REFERENCES exp_category(category_code),
    CONSTRAINT chk_exp_item_amt_pos CHECK (amount > 0.00)
);

-- 5. Audit Trail Table (BR-EXP-008)
CREATE TABLE exp_approval_action (
    action_id           NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_id            NUMBER         NOT NULL,
    actor_username      VARCHAR2(100)  NOT NULL,
    action_type         VARCHAR2(30)   NOT NULL,
    action_stage        VARCHAR2(30)   NOT NULL,
    action_timestamp    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    reason_comments     VARCHAR2(4000),
    CONSTRAINT pk_exp_appr_action PRIMARY KEY (action_id),
    CONSTRAINT fk_exp_action_claim FOREIGN KEY (claim_id) REFERENCES exp_claim(claim_id),
    CONSTRAINT chk_exp_action_type CHECK (action_type IN ('SUBMITTED', 'ENDORSED', 'APPROVED', 'REJECTED', 'RESUBMITTED')),
    CONSTRAINT chk_exp_action_stage CHECK (action_stage IN ('NONE', 'EMPLOYEE', 'MANAGER', 'DIRECTOR'))
);

-- Performance and Foreign Key Indexes
CREATE INDEX idx_exp_claim_subm_stat ON exp_claim(submitter_username, current_status);
CREATE INDEX idx_exp_claim_status_appr ON exp_claim(current_status, assigned_approver);
CREATE INDEX idx_exp_item_claim ON exp_claim_item(claim_id);
CREATE INDEX idx_exp_action_claim ON exp_approval_action(claim_id, action_timestamp);
CREATE INDEX idx_exp_user_mgr ON exp_user_profile(manager_username);
CREATE INDEX idx_exp_user_dir ON exp_user_profile(director_username);

